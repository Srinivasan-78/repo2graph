#!/usr/bin/env python3
"""Generate the VS Code extension's copy of repo2graph's own tables (#400).

The extension in `editors/vscode/` needs three tables the Python package
already owns: which file extensions repo2graph parses (and as what), the node
types, and the edge types. Typing them into TypeScript by hand is how they
drift -- a language added to `parse.EXT_LANG` would leave the extension
calling that language's files unsupported. So the TypeScript module is
generated from the Python tables, and `tests/test_vscode_extension.py` fails
until it is regenerated after either side moves.

Usage:
    python scripts/generate_vscode_tables.py           # print the module
    python scripts/generate_vscode_tables.py --write   # rewrite it in place
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / "editors" / "vscode" / "src" / "core" / "generated.ts"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))


def _record(name: str, doc: str, table: dict[str, str]) -> list[str]:
    lines = [f"/** {doc} */", f"export const {name}: Readonly<Record<string, string>> = {{"]
    lines += [f"  {json.dumps(key)}: {json.dumps(value)}," for key, value in table.items()]
    return [*lines, "};", ""]


def render() -> str:
    """The generated module's full text."""
    from repo2graph.parse import EXT_LANG, LANG_CFG
    from repo2graph.viz import EDGE_TYPES, NODE_TYPES, REFERENCE_EDGE_TYPES

    lines = [
        "// Generated by scripts/generate_vscode_tables.py from repo2graph's own tables.",
        "// Do not edit: tests/test_vscode_extension.py fails when this file and the",
        "// Python tables disagree. Regenerate with:",
        "//   python scripts/generate_vscode_tables.py --write",
        "",
    ]
    lines += _record(
        "EXT_LANG",
        "File extension -> the language repo2graph reads it as (repo2graph.parse.EXT_LANG).",
        dict(EXT_LANG),
    )
    lines += [
        "/** Languages with a grammar of their own (repo2graph.parse.LANG_CFG). */",
        "export const LANGUAGES: readonly string[] = [",
        *[f"  {json.dumps(lang)}," for lang in sorted(LANG_CFG)],
        "];",
        "",
    ]
    lines += _record(
        "NODE_TYPES",
        "Node types and what each one is (repo2graph.viz.NODE_TYPES).",
        dict(NODE_TYPES),
    )
    lines += _record(
        "EDGE_TYPES",
        "Edge types and what each one is (repo2graph.viz.EDGE_TYPES, REFERENCE_EDGE_TYPES).",
        {**EDGE_TYPES, **REFERENCE_EDGE_TYPES},
    )
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--write" in argv[1:]:
        with open(TARGET, "w", encoding="utf8", newline="\n") as fh:
            fh.write(text)
        print(f"wrote {TARGET.relative_to(ROOT).as_posix()}")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
